class Loss_PSNR(nn.Module):
    def __init__(self):
        super(Loss_PSNR, self).__init__()

    def forward(self, im_true, im_fake, data_range=4095):
        N = im_true.size()[0]
        C = im_true.size()[1]
        H = im_true.size()[2]
        W = im_true.size()[3]
        Itrue = im_true.clamp(0., 16.).mul_(data_range)
        Ifake = im_fake.clamp(0., 16.).mul_(data_range)

        mse_c = (Itrue - Ifake).pow(2).mean(dim=(2, 3))
        psnr_c = 10.0 * torch.log10(65535.**2/mse_c)
        psnr = psnr_c.mean(dim=1).mean()
        return psnr

